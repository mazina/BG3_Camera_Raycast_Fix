struct Operand { std::size_t offset; std::uint8_t normal, position; };
constexpr Operand Operands[] = {
    {0x194, 0x84, 0x90}, // compare hit.Position.y, not hit.Normal.y
    {0x1a4, 0x88, 0x94}, // copy hit.Position.z
    {0x1a9, 0x80, 0x8c}, // copy hit.Position.xy
};
static_assert(std::size(Signature) == 0x1d0);
Match Inspect(std::uint8_t const* code) {
    unsigned original = 0, corrected = 0;
    for (std::size_t i = 0; i < std::size(Signature); ++i) {
        bool operand = false;
        for (auto const& field : Operands) if (field.offset == i) {
            original += code[i] == field.normal;
            corrected += code[i] == field.position;
            operand = true;
        }
        if (!operand && Signature[i] >= 0 && code[i] != Signature[i]) return Match::Absent;
    }
    if (original == std::size(Operands)) return Match::Original;
    if (corrected == std::size(Operands)) return Match::Corrected;
    return Match::Absent; // Partial or conflicting modifications are unsupported.
}

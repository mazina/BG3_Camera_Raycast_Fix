Match Find(std::span<std::uint8_t const> text, std::size_t& offset) {
    constexpr std::uint8_t anchor[] = {0x48,0x89,0x5c,0x24,0x10,0x48,0x89,0x74,0x24,0x18,0x48,0x89,0x7c,0x24,0x20,0x55};
    Match result = Match::Absent;
    auto cursor = text.begin();
    while (cursor != text.end()) {
        auto hit = std::search(cursor, text.end(), std::begin(anchor), std::end(anchor));
        if (hit == text.end() || static_cast<std::size_t>(text.end() - hit) < std::size(Signature)) break;
        auto match = Inspect(&*hit);
        if (match != Match::Absent) {
            if (result != Match::Absent) return Match::Ambiguous;
            result = match;
            offset = static_cast<std::size_t>(hit - text.begin());
        }
        cursor = hit + 1;
    }
    return result;
}

bool Patch::Prepare(HMODULE game, std::string& reason) {
    if (function_ || applied_) { reason = "patch already prepared"; return false; }
    if (!game) { reason = "game module unavailable"; return false; }
    auto base = reinterpret_cast<std::uint8_t*>(game);
    auto dos = reinterpret_cast<IMAGE_DOS_HEADER const*>(base);
    if (dos->e_magic != IMAGE_DOS_SIGNATURE || dos->e_lfanew < 0) { reason = "invalid game image"; return false; }
    auto nt = reinterpret_cast<IMAGE_NT_HEADERS64 const*>(base + dos->e_lfanew);
    if (nt->Signature != IMAGE_NT_SIGNATURE || nt->FileHeader.Machine != IMAGE_FILE_MACHINE_AMD64
        || nt->OptionalHeader.Magic != IMAGE_NT_OPTIONAL_HDR64_MAGIC) { reason = "unsupported game image"; return false; }
    auto section = IMAGE_FIRST_SECTION(nt);
    std::uint8_t* selected = nullptr;
    std::uint32_t selectedRva = 0;
    Match selectedMatch = Match::Absent;
    for (unsigned i = 0; i < nt->FileHeader.NumberOfSections; ++i) {
        if (!(section[i].Characteristics & IMAGE_SCN_MEM_EXECUTE)) continue;
        std::size_t start = section[i].VirtualAddress;
        std::size_t size = std::max(section[i].Misc.VirtualSize, section[i].SizeOfRawData);
        if (start > nt->OptionalHeader.SizeOfImage || size > nt->OptionalHeader.SizeOfImage - start) {
            reason = "invalid executable section"; return false;
        }
        std::size_t offset = 0;
        auto match = Find({base + start, size}, offset);
        if (match == Match::Ambiguous || (match != Match::Absent && selected)) {
            reason = "ambiguous avoidance helper"; return false;
        }
        if (match != Match::Absent) {
            selected = base + start + offset;
            selectedRva = static_cast<std::uint32_t>(start + offset);
            selectedMatch = match;
        }
    }
    if (!selected) { reason = "avoidance helper instruction shape unsupported or modified"; return false; }
    function_ = selected; functionRva_ = selectedRva;
    alreadyCorrected_ = selectedMatch == Match::Corrected;
    return true;
}

bool Patch::ContainsInstruction(std::uintptr_t ip) const {
    auto start = reinterpret_cast<std::uintptr_t>(function_);
    return function_ && ip >= start && ip - start < std::size(Signature);
}

bool Patch::Apply() {
    if (!function_) return false;
    if (alreadyCorrected_ || applied_) return Inspect(function_) == Match::Corrected;
    if (Inspect(function_) != Match::Original) return false;
    DWORD protection = 0, ignored = 0;
    if (!VirtualProtect(function_, std::size(Signature), PAGE_EXECUTE_READWRITE, &protection)) return false;
    for (auto const& field : Operands) function_[field.offset] = field.position;
    originalProtection_ = protection;
    applied_ = true;
    bool flushed = FlushInstructionCache(GetCurrentProcess(), function_, std::size(Signature)) != FALSE;
    bool protectedAgain = VirtualProtect(function_, std::size(Signature), protection, &ignored) != FALSE;
    return flushed && protectedAgain;
}

bool Patch::Rollback() {
    if (!applied_) return true;
    // A previous rollback may have restored the bytes but failed to flush
    // the instruction cache or restore page protection. Retain ownership
    // until those finalization steps succeed so the caller can retry.
    auto current = Inspect(function_);
    if (current != Match::Corrected && current != Match::Original) return false;
    DWORD protection = 0, ignored = 0;
    if (!VirtualProtect(function_, std::size(Signature), PAGE_EXECUTE_READWRITE, &protection)) return false;
    for (auto const& field : Operands) function_[field.offset] = field.normal;
    bool flushed = FlushInstructionCache(GetCurrentProcess(), function_, std::size(Signature)) != FALSE;
    bool protectedAgain = VirtualProtect(function_, std::size(Signature), originalProtection_, &ignored) != FALSE;
    if (flushed && protectedAgain) applied_ = false;
    return flushed && protectedAgain;
}
